def p(text):
    return doc.add_paragraph(text)

def page(title):
    h = doc.add_heading(title, 1)
    h.paragraph_format.page_break_before = True

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.autofit = False
    if widths:
        scale = 7.1 / sum(widths)
        widths = [w * scale for w in widths]
        for col, width in zip(t.columns, widths): col.width = Inches(width)
    for c, text in zip(t.rows[0].cells, headers):
        c.text = text
        sh = OxmlElement('w:shd'); sh.set(qn('w:fill'), 'DDEBF7'); c._tc.get_or_add_tcPr().append(sh)
    rep = OxmlElement('w:tblHeader'); t.rows[0]._tr.get_or_add_trPr().append(rep)
    for row in rows:
        for c, text in zip(t.add_row().cells, row): c.text = str(text)
    for row in t.rows:
        cant = OxmlElement('w:cantSplit'); row._tr.get_or_add_trPr().append(cant)
        for i, c in enumerate(row.cells):
            if widths: c.width = Inches(widths[i])
            pr = c._tc.get_or_add_tcPr()
            b = OxmlElement('w:tcBorders')
            for side in ['top', 'left', 'bottom', 'right']:
                e = OxmlElement('w:'+side); e.set(qn('w:val'), 'single'); e.set(qn('w:sz'), '4'); e.set(qn('w:color'), 'D9D9D9'); b.append(e)
            pr.append(b)
            for para in c.paragraphs:
                para.paragraph_format.space_after = Pt(2)
                para.paragraph_format.space_before = Pt(2)
    return t

