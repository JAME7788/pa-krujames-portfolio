def p(text='', style=None, bold=None, center=False):
    para = doc.add_paragraph(style=style)
    r = para.add_run(text); r.bold = bold
    if center: para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.paragraph_format.widow_control = True
    return para

def h(text, level=2): return doc.add_heading(text, level)
def page(title, level=1):
    para = p(title, 'Contents Heading') if title == 'สารบัญ' else h(title, level)
    para.paragraph_format.page_break_before = True
    return para
def label(title, text):
    para = p()
    para.add_run(title+' ').bold=True
    para.add_run(text)
    return para
def table(headers, rows, widths, size=14):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for col,width in zip(t.columns,widths): col.width=Cm(width)
    borders = OxmlElement('w:tblBorders')
    for edge in ['top','left','bottom','right','insideH','insideV']:
        b=OxmlElement('w:'+edge); b.set(qn('w:val'),'single'); b.set(qn('w:sz'),'4'); b.set(qn('w:color'),'D9D9D9'); borders.append(b)
    t._tbl.tblPr.append(borders)
    for i,row in enumerate([headers]+rows):
        cells = t.rows[0].cells if i==0 else t.add_row().cells
        trpr=t.rows[i]._tr.get_or_add_trPr()
        cant=OxmlElement('w:cantSplit'); trpr.append(cant)
        if i==0:
            repeat=OxmlElement('w:tblHeader'); trpr.append(repeat)
        for j,(cell,text,width) in enumerate(zip(cells,row,widths)):
            cell.width=Cm(width); cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            cell.text=str(text)
            pr=cell._tc.get_or_add_tcPr()
            mar=OxmlElement('w:tcMar')
            for side in ['top','left','bottom','right']:
                e=OxmlElement('w:'+side); e.set(qn('w:w'),'50'); e.set(qn('w:type'),'dxa'); mar.append(e)
            pr.append(mar)
            if i==0 or i%2==0:
                shade=OxmlElement('w:shd'); shade.set(qn('w:fill'),'E8EBEE' if i==0 else 'F7F8F9'); pr.append(shade)
            for para in cell.paragraphs:
                para.paragraph_format.space_after=Pt(1)
                para.paragraph_format.line_spacing=1.0
                if width < 2.0: para.alignment=WD_ALIGN_PARAGRAPH.CENTER
                for run in para.runs:
                    run.font.size=Pt(size); run.bold=i==0
    gap=p()
    gap.paragraph_format.space_after=Pt(2)
    gap.paragraph_format.line_spacing=Pt(2)
    gap.add_run().font.size=Pt(2)
    return t

