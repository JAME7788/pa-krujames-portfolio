def shade(cell, color):
    tcPr = cell._tc.get_or_add_tcPr(); shd = OxmlElement('w:shd'); shd.set(qn('w:fill'), color); tcPr.append(shd)

def borders(table):
    tblPr = table._tbl.tblPr
    b = OxmlElement('w:tblBorders')
    for edge in ('top','left','bottom','right','insideH','insideV'):
        e = OxmlElement(f'w:{edge}'); e.set(qn('w:val'),'single'); e.set(qn('w:sz'),'4'); e.set(qn('w:color'),'D9D9D9'); b.append(e)
    tblPr.append(b)

def repeat_header(row):
    trPr = row._tr.get_or_add_trPr()
    marker = OxmlElement('w:tblHeader')
    marker.set(qn('w:val'), 'true')
    trPr.append(marker)

def p(text='', bold=False, size=None, align=None, color=None, before=0, after=5):
    par = doc.add_paragraph(); par.paragraph_format.space_before = Pt(before); par.paragraph_format.space_after = Pt(after)
    if align is not None: par.alignment = align
    run = par.add_run(text); run.bold = bold
    if size: run.font.size = Pt(size)
    if color: run.font.color.rgb = RGBColor.from_string(color)
    run.font.name = 'TH Sarabun New'; run._element.rPr.rFonts.set(qn('w:eastAsia'), 'TH Sarabun New')
    return par

def heading(text, level=1):
    par = p(text, bold=True, size=21 if level == 1 else 18, color=RED, before=8, after=7)
    return par

def bullets(items):
    for item in items:
        par = doc.add_paragraph(style='Normal'); par.style = doc.styles['Normal']; par.paragraph_format.left_indent = Inches(.24); par.paragraph_format.first_line_indent = Inches(-.16)
        par.add_run('• ').bold = True; par.add_run(item)

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers)); t.alignment = WD_TABLE_ALIGNMENT.CENTER; t.autofit = False; borders(t)
    for i,h in enumerate(headers):
        c=t.rows[0].cells[i]; c.text=h; shade(c, RED); c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
        for r in c.paragraphs[0].runs: r.font.color.rgb=RGBColor(255,255,255); r.bold=True; r.font.size=Pt(14)
        if widths: c.width=Inches(widths[i])
    repeat_header(t.rows[0])
    for ri,row in enumerate(rows):
        cells=t.add_row().cells
        for i,val in enumerate(row):
            cells[i].text=str(val); cells[i].vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if widths: cells[i].width=Inches(widths[i])
            if ri % 2 == 1: shade(cells[i], LIGHT)
            for par in cells[i].paragraphs:
                par.paragraph_format.space_after=Pt(2); par.paragraph_format.space_before=Pt(2)
                for r in par.runs: r.font.size=Pt(13)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

